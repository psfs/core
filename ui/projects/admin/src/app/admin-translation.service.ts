@Injectable({ providedIn: 'root' })
export class AdminTranslationService {
  private readonly activeLocale = signal('en_US');

  setLocale(locale: string): void {
    this.activeLocale.set(locale);
  }

  translate(value: string, parameters: Record<string, string | number> = {}): string {
    const translated = this.activeLocale().startsWith('es')
      ? SPANISH[value] ?? value
      : ENGLISH[value] ?? value;
    return translated.replace(/\{\{\s*(\w+)\s*\}\}/g, (placeholder, name: string) =>
      Object.hasOwn(parameters, name) ? String(parameters[name]) : placeholder
    );
  }
}
